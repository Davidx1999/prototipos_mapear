import fs from 'fs';
import path from 'path';

const TOKENS_DIR = path.resolve('src/components/variables_Figma');
const OUTPUT_FILE = path.resolve('src/styles/figma-variables.css');

const files = fs.readdirSync(TOKENS_DIR).filter(file => file.endsWith('.json'));

let cssContent = `/* 
  AUTO-GENERATED BY generate-figma-css.js
  Do not edit manually. 
*/\n\n`;

function toKebabCase(str) {
  return str.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/[\s_]+/g, '-').toLowerCase();
}

function traverse(obj, currentPath = []) {
  let variables = {};
  
  if (obj && obj['$value'] !== undefined) {
    const val = obj['$value'];
    const type = obj['$type'];
    
    let cssValue = val;
    
    if (type === 'color' && typeof val === 'object' && val.hex) {
      cssValue = val.hex;
    } else if (typeof val === 'number') {
      // Avoid adding px to fontWeight or opacity
      const name = currentPath.join('-').toLowerCase();
      if (name.includes('font-weight') || name.includes('opacity') || name.includes('line-height') && val < 10) {
        cssValue = val;
      } else {
        cssValue = val + 'px';
      }
    } else if (typeof val === 'string' && val.startsWith('{') && val.endsWith('}')) {
      // Aliases: "{color.brand.50}" -> "var(--color-brand-50)"
      const aliasPath = val.replace(/[{}]/g, '').split('.').map(toKebabCase).join('-');
      cssValue = `var(--${aliasPath})`;
    } else if (typeof val === 'object') {
        // Fallback for complex values that are just strings/objects
        if(val.hex) cssValue = val.hex;
        else if (val.fontFamily) {
           // example typography object
           return {
              [`${currentPath.join('-')}-font-family`]: val.fontFamily,
              [`${currentPath.join('-')}-font-weight`]: val.fontWeight,
              [`${currentPath.join('-')}-line-height`]: val.lineHeight + (typeof val.lineHeight === 'number' && val.lineHeight > 10 ? 'px' : ''),
              [`${currentPath.join('-')}-font-size`]: val.fontSize + 'px'
           };
        }
    }

    variables[currentPath.join('-')] = cssValue;
    return variables;
  }
  
  for (const key in obj) {
    if (key === '$extensions' || key === '$type' || key === '$description') continue;
    if (typeof obj[key] === 'object') {
      const nested = traverse(obj[key], [...currentPath, toKebabCase(key)]);
      variables = { ...variables, ...nested };
    }
  }
  
  return variables;
}

function processThemeFile(filename, scopeSelector) {
  const data = JSON.parse(fs.readFileSync(path.join(TOKENS_DIR, filename), 'utf-8'));
  const vars = traverse(data);
  let css = `${scopeSelector} {\n`;
  for (const [key, value] of Object.entries(vars)) {
    css += `  --${key}: ${value};\n`;
  }
  css += `}\n\n`;
  return css;
}

// Global (font-family, maybe some shared tokens)
if (files.includes('font-family.tokens.json')) {
  cssContent += processThemeFile('font-family.tokens.json', ':root');
}

// Desktop / Tablet / Mobile (Responsive)
if (files.includes('Desktop.tokens.json')) {
  let desktopCss = processThemeFile('Desktop.tokens.json', '@media (min-width: 1024px) {\n  :root');
  desktopCss = desktopCss.replace(/}\n\n$/, '  }\n}\n\n');
  cssContent += desktopCss;
}
if (files.includes('Tablet.tokens.json')) {
  let tabletCss = processThemeFile('Tablet.tokens.json', '@media (min-width: 768px) and (max-width: 1023px) {\n  :root');
  tabletCss = tabletCss.replace(/}\n\n$/, '  }\n}\n\n');
  cssContent += tabletCss;
}
if (files.includes('Mobile.tokens.json')) {
  let mobileCss = processThemeFile('Mobile.tokens.json', '@media (max-width: 767px) {\n  :root');
  mobileCss = mobileCss.replace(/}\n\n$/, '  }\n}\n\n');
  cssContent += mobileCss;
}

// Themes
const themes = [
  { file: 'CEnPE Light.tokens.json', selector: ':root, [data-theme="cenpe"][data-color-scheme="light"]' },
  { file: 'CEnPE Dark.tokens.json', selector: '[data-theme="cenpe"][data-color-scheme="dark"]' },
  { file: 'FGV Light.tokens.json', selector: '[data-theme="fgv"][data-color-scheme="light"]' },
  { file: 'FGV Dark.tokens.json', selector: '[data-theme="fgv"][data-color-scheme="dark"]' }
];

for (const theme of themes) {
  if (files.includes(theme.file)) {
    cssContent += processThemeFile(theme.file, theme.selector);
  }
}

// Ensure styles directory exists
if (!fs.existsSync(path.resolve('src/styles'))) {
  fs.mkdirSync(path.resolve('src/styles'), { recursive: true });
}

fs.writeFileSync(OUTPUT_FILE, cssContent);
console.log(`Generated ${OUTPUT_FILE} successfully!`);
